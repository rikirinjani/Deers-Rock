#!/usr/bin/env bash
# r2_wave2.sh — R2-4 gate-fail proof + R2-3 single-pool prefix-size latency curve.
# Logs/artifacts: p-chain/r2_gatefail.md, p3_latency_curve.md, p3_curve.json,
# p-chain/r2_wave2.log. Scratch RUN_ID r2inject for gate logs.
set -uo pipefail
OUT=/opt/dr-benchmark/p-chain
TOOLS=/opt/Deers-Rock/tools
LOG=$OUT/r2_wave2.log
: > "$LOG"
ts(){ date -u +%H:%M:%S; }
say(){ echo "[$(ts)] $*" >> "$LOG"; }
say "=== R2 wave2 start ==="

# ---------------- R2-4: gate-fail proof ----------------
python3 /tmp/r2_inject.py verify >> "$LOG"
say "--- inject ---"
python3 /tmp/r2_inject.py inject >> "$LOG" 2>&1 || { say "INJECT FAILED - aborting wave2 gate part"; }

run_gate(){ # label, cmd...
  local L=$1; shift
  say "--- gate: $L"
  set -o pipefail; "$@" 2>&1 | tee -a "$OUT/r2_gate_${L}.log"; local RC=${PIPESTATUS[0]}; set +o pipefail
  say "gate $L rc=$RC"
  return $RC
}

# three-count: expect FAIL + GAP reason codes
run_gate three_count env RUN_ID=r2inject python3 $TOOLS/three_count_reconcile.py --stage B1; RC_TC=$?
# charge-delta: expect FAIL + UNEXPLAINED
run_gate charge_delta env RUN_ID=r2inject python3 $TOOLS/charge_delta_per_component.py --stage B1; RC_CD=$?
# billed_eq_dr with only 899001 (billed): expect PASS
run_gate billed_eq_1 bash -c "source $OUT/p2_gate_extract.sh; check_billed_eq_dr"; RC_BE1=$?
say "phase-1 gate rcs: three_count=$RC_TC charge_delta=$RC_CD billed_eq=$RC_BE1"

# second injection: reg-only visit -> billed_eq_dr must FAIL with UNBILLED-2026/10
python3 /tmp/r2_inject.py inject2 >> "$LOG"
run_gate billed_eq_2 bash -c "source $OUT/p2_gate_extract.sh; check_billed_eq_dr"; RC_BE2=$?
say "phase-2 gate rc (expect non-zero): billed_eq=$RC_BE2"

say "--- cleanup ---"
python3 /tmp/r2_inject.py cleanup >> "$LOG"
python3 /tmp/r2_inject.py verify >> "$LOG"

# post-cleanup: all gates PASS again
run_gate three_count_post env RUN_ID=r2inject python3 $TOOLS/three_count_reconcile.py --stage B1; RC_TC2=$?
run_gate charge_delta_post env RUN_ID=r2inject python3 $TOOLS/charge_delta_per_component.py --stage B1; RC_CD2=$?
run_gate billed_eq_post bash -c "source $OUT/p2_gate_extract.sh; check_billed_eq_dr"; RC_BE3=$?
say "post-cleanup gate rcs: three_count=$RC_TC2 charge_delta=$RC_CD2 billed_eq=$RC_BE3"

# ---------------- R2-4 report ----------------
python3 - "$OUT" >> "$LOG" 2>&1 <<'PY'
