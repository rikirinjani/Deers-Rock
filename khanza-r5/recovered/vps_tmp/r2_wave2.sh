    except OSError:
        return ["(log missing)"]
    out = []
    for p in pats:
        out += ["    " + l.strip() for l in t.splitlines() if re.search(p, l)]
    return out or ["    (no matching line)"]
tc = harvest(OUT + "/r2_gate_three_count.log",
             [r"GAP \[", r"three-count reconcile (PASS|FAIL)"])
cd = harvest(OUT + "/r2_gate_charge_delta.log",
             [r"UNEXPLAINED", r"unexplained-delta count", r"charge delta (PASS|FAIL)"])
be1 = harvest(OUT + "/r2_gate_billed_eq_1.log", [r"UNBILLED-", r"INvariant|GATE"])
be2 = harvest(OUT + "/r2_gate_billed_eq_2.log", [r"UNBILLED-"])
be3 = harvest(OUT + "/r2_gate_billed_eq_post.log", [r"UNBILLED-"])
tcp = harvest(OUT + "/r2_gate_three_count_post.log", [r"no gaps", r"three-count reconcile PASS"])
cdp = harvest(OUT + "/r2_gate_charge_delta_post.log", [r"unexplained-delta count: 0", r"charge delta PASS"])
L = ["# R2-4 — gate-fail proof (fault injection + restore)",
     "",
     "Injected scratch visit `2026/10/05/899001` (DR099901): reg row + ledger rows",
     "(registration @ **99999** — wrong price vs khanza 10000; drug **XX9999** @ 500 —",
     "code NOT in databarang) + one billing Registrasi value row @ 10000 (mismatch).",
     "Plus `2026/10/05/899002` (reg row ONLY — unbilled).",
     "",
     "## Gates under injection (expected to FAIL / fire reason codes)",
     "",
     "### three_count_reconcile --stage B1 (rc!=0 = FAIL as designed)", "```"] + tc + \
    ["```", "", "### charge_delta_per_component --stage B1 (rc!=0 = FAIL as designed)", "```"] + cd + \
    ["```", "", "### check_billed_eq_dr with 899001 billed only (expect PASS — invariant holds)", "```"] + be1 + \
    ["```", "", "### check_billed_eq_dr with 899002 reg-only (expect UNBILLED-2026/10)", "```"] + be2 + \
    ["```", "", "## After exact-scope cleanup (expect all PASS again)", "```"] + tcp + cdp + be3 + \
    ["```", "",
     "State counts (pre-inject / post-inject / post-cleanup) are in r2_wave2.log",
     "(verify lines). Every injected row was deleted by exact no_rawat scope",
     "(`2026/10/05/899001`, `2026/10/05/899002`) from reg_periksa, billing and",
     "dr_charge_ledger; nothing else touched.",
     "", "_Generated by r2_wave2.sh_" ]
open(OUT + "/r2_gatefail.md", "w").write("\n".join(L) + "\n")
print("r2_gatefail.md written")
PY

# ---------------- R2-3: prefix-size latency curve (single tuned pool) ----------------
python3 - "$OUT" >> "$LOG" 2>&1 <<'PY'
import json, subprocess, sys, time
OUT = sys.argv[1]
def q(sql, db="sik"):
    return subprocess.run(["mysql", "-uroot", db, "-N", "-B", "-e", sql],
                          capture_output=True, text=True, timeout=900)
# real cumulative cutoffs
rows = q("SELECT tgl_registrasi, COUNT(*) FROM reg_periksa WHERE no_rkm_medis "
         "LIKE 'DR%' GROUP BY tgl_registrasi ORDER BY tgl_registrasi").stdout
cum, total, cutoffs = 0, 0, {}
for line in rows.strip().splitlines():
    d, n = line.split("\t"); n = int(n); cum += n; total += n
    for target in (10000, 30000, 60000):
        if target not in cutoffs and cum >= target:
            cutoffs[target] = d
print("total DR visits=%d cutoffs=%s" % (total, cutoffs))
BASE = {
 "visits_by_clinic": "SELECT p.nm_poli, COUNT(*) FROM reg_periksa r JOIN poliklinik p ON p.kd_poli=r.kd_poli WHERE r.no_rkm_medis LIKE 'DR%' GROUP BY p.nm_poli ORDER BY 2 DESC",
 "visits_by_day": "SELECT tgl_registrasi, COUNT(*) FROM reg_periksa WHERE no_rkm_medis LIKE 'DR%' GROUP BY tgl_registrasi ORDER BY tgl_registrasi",
 "visits_by_doctor": "SELECT d.nm_dokter, COUNT(*) FROM reg_periksa r JOIN dokter d ON d.kd_dokter=r.kd_dokter WHERE r.no_rkm_medis LIKE 'DR%' GROUP BY d.nm_dokter ORDER BY 2 DESC LIMIT 50",
 "revenue_by_month": "SELECT DATE_FORMAT(r.tgl_registrasi,'%Y-%m') per, ROUND(SUM(b.totalbiaya),2) FROM billing b JOIN reg_periksa r ON r.no_rawat=b.no_rawat WHERE r.no_rkm_medis LIKE 'DR%' AND (b.biaya>0 OR b.totalbiaya>0) AND b.status NOT LIKE 'Ttl%' GROUP BY per ORDER BY per",
 "revenue_by_clinic": "SELECT p.nm_poli, ROUND(SUM(b.totalbiaya),2) FROM billing b JOIN reg_periksa r ON r.no_rawat=b.no_rawat JOIN poliklinik p ON p.kd_poli=r.kd_poli WHERE r.no_rkm_medis LIKE 'DR%' AND (b.biaya>0 OR b.totalbiaya>0) AND b.status NOT LIKE 'Ttl%' GROUP BY p.nm_poli ORDER BY 2 DESC",
 "drug_usage_top20": "SELECT db.nama_brng, COUNT(*), SUM(d.jml), ROUND(SUM(d.total),2) FROM detail_pemberian_obat d JOIN reg_periksa r ON r.no_rawat=d.no_rawat JOIN databarang db ON db.kode_brng=d.kode_brng WHERE r.no_rkm_medis LIKE 'DR%' GROUP BY db.nama_brng ORDER BY 4 DESC LIMIT 20",
 "top_diagnoses": "SELECT pk.nm_penyakit, COUNT(*) FROM reg_periksa r LEFT JOIN diagnosa_pasien dp ON dp.no_rawat=r.no_rawat LEFT JOIN penyakit pk ON pk.kd_penyakit=dp.kd_penyakit WHERE r.no_rkm_medis LIKE 'DR%' AND pk.nm_penyakit IS NOT NULL GROUP BY pk.nm_penyakit ORDER BY 2 DESC LIMIT 20",
 "top_billed_visits": "SELECT b.no_rawat, ROUND(SUM(b.totalbiaya),2) FROM billing b JOIN reg_periksa r ON r.no_rawat=b.no_rawat WHERE r.no_rkm_medis LIKE 'DR%' AND (b.biaya>0 OR b.totalbiaya>0) AND b.status NOT LIKE 'Ttl%' GROUP BY b.no_rawat ORDER BY 2 DESC LIMIT 100",
}
def cutsql(name, d):
    s = BASE[name]
    if name == "visits_by_day":
        return s.replace("no_rkm_medis LIKE 'DR%'",
                         "no_rkm_medis LIKE 'DR%' AND tgl_registrasi <= '%s'" % d, 1)
    return s.replace("no_rkm_medis LIKE 'DR%'",
                     "no_rkm_medis LIKE 'DR%' AND r.tgl_registrasi <= '%s'" % d, 1)
def pct(st, x):
    return round(st[min(len(st)-1, int(round(x*(len(st)-1))))],1) if st else None
old_lqt = q("SELECT @@long_query_time").stdout.strip()
subprocess.run(["mysql","-uroot","-e","SET GLOBAL long_query_time=1;"])
print("long_query_time: %s -> 1" % old_lqt)
sizes = [("~10k", cutoffs.get(10000)), ("~30k", cutoffs.get(30000)),
         ("~60k", cutoffs.get(60000)), ("~86k (full)", None)]
res = {}
for label, d in sizes:
    sq0 = int(q("SHOW GLOBAL STATUS LIKE 'Slow_queries'").stdout.split("\t")[1])
    for name in BASE:
        sql = cutsql(name, d) if d else BASE[name]
        times = []
        for _ in range(20):
            t0 = time.perf_counter(); p = q(sql); dt = (time.perf_counter()-t0)*1000
            if p.returncode == 0: times.append(dt)
        st = sorted(times)
        res.setdefault(label, {})[name] = {"runs": len(times), "p50": pct(st,.5),
            "p95": pct(st,.95), "p99": pct(st,.99)}
        print("  %-12s %-20s p50=%-8s p95=%-8s p99=%s" % (label, name,
              res[label][name]["p50"], res[label][name]["p95"], res[label][name]["p99"]), flush=True)
    sq1 = int(q("SHOW GLOBAL STATUS LIKE 'Slow_queries'").stdout.split("\t")[1])
    res[label]["_slow_delta_1s"] = sq1 - sq0
    res[label]["_cutoff"] = d or "full"
    print("  %s slow-query delta @1s: %d" % (label, sq1 - sq0), flush=True)
subprocess.run(["mysql","-uroot","-e","SET GLOBAL long_query_time=%s;" % old_lqt])
print("long_query_time restored to %s" % old_lqt)
json.dump({"long_query_time_during": 1, "long_query_time_restored": old_lqt,
           "pool_bytes": int(q("SELECT @@innodb_buffer_pool_size").stdout),
           "sizes": res}, open(OUT + "/p3_curve.json", "w"), indent=1)
L = ["# R2-3 — staged-size latency curve at ONE pool config",
     "",
     "**Honest label:** prefix-size proxy at a single tuned pool (3.2 GB), 20 runs per",
     "point, long_query_time=1 s during measurement (restored to 10 s after). The",
     "restore step is a logging-only stub, so rungs cannot be rebuilt from scratch;",
     "sizes are data-prefix approximations of cumulative DB growth (cutoff dates from",
     "real cumulative reg_periksa counts: 10k=%s, 30k=%s, 60k=%s; full=%d visits)."
     % (cutoffs.get(10000), cutoffs.get(30000), cutoffs.get(60000), total),
     "", "| size | query | p50 ms | p95 ms | p99 ms |", "|---|---|---|---|---|"]
for label, _d in sizes:
    for name in BASE:
        r = res[label][name]
        L.append("| %s | %s | %s | %s | %s |" % (label, name, r["p50"], r["p95"], r["p99"]))
    L.append("| %s | _slow-query delta @1 s_ | | | **%d** |" % (label, res[label]["_slow_delta_1s"]))
L += ["", "_Raw: p-chain/p3_curve.json. Generated by r2_wave2.sh_"]
open(OUT + "/p3_latency_curve.md", "w").write("\n".join(L) + "\n")
print("p3_latency_curve.md written")
PY

say "=== R2 wave2 done ==="
echo done > /tmp/r2w2.done
